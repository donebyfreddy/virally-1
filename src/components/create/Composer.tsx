/** The brief input and its source actions. */
function BriefCard({
  prompt,
  onPromptChange,
  promptReady,
}: {
  prompt: string;
  onPromptChange: (next: string) => void;
  promptReady: boolean;
}) {
  return (
    <Card as="section" aria-labelledby="brief-heading">
      <CardHeader id="brief-heading" as="h2" title={briefPanelCopy.heading} />

      <CardBody className="pt-[var(--space-3)]">
        {/* A real label, not placeholder-only instruction, and the hint below it
            is rendered for everyone — essential instructions never live only in
            a placeholder. */}
        <div className="flex items-baseline justify-between gap-[var(--space-4)]">
          <label htmlFor="campaign-brief" className={labelClasses}>
            {createCopy.promptLabel}
          </label>
          <span
            className={cn(
              "app-figure text-[length:var(--text-app-label)]",
              prompt.length > BRIEF_MAX * 0.9
                ? "text-[color:var(--warning)]"
                : "text-[color:var(--text-muted)]",
            )}
          >
            {prompt.length.toLocaleString("en-US")} / {BRIEF_MAX.toLocaleString("en-US")}
          </span>
        </div>

        <textarea
          id="campaign-brief"
          name="promptVisible"
          rows={7}
          value={prompt}
          maxLength={BRIEF_MAX}
          onChange={(event) => onPromptChange(event.target.value)}
          aria-describedby="campaign-brief-hint"
          placeholder={createCopy.examples[0]}
          className={cn(
            "mt-[var(--space-2)] w-full resize-y rounded-[var(--radius-control)]",
            "border border-[var(--border-default)] bg-[var(--surface-primary)] p-[var(--space-3)]",
            "[font-family:inherit] text-[length:var(--text-app-body)] text-[color:var(--text-primary)]",
            "placeholder:text-[color:var(--text-muted)]",
            "transition-colors duration-[var(--dur-instant)]",
            "hover:border-[var(--border-strong)]",
            "focus:border-[var(--brand-primary)] focus:outline-2 focus:outline-offset-1 focus:outline-[var(--focus-ring)]",
          )}
        />

        <p id="campaign-brief-hint" className={cn("mt-[var(--space-2)]", hintClasses)}>
          {createCopy.promptHint}
        </p>

        {!promptReady && prompt.length > 0 && (
          <p className="mt-[var(--space-2)] text-[length:var(--text-app-label)] text-[color:var(--warning)]">
            Write at least ten characters to continue.
          </p>
        )}

        {/* Source actions. Disabled and labelled rather than hidden, with the
            reason stated: the product will accept these sources, and a disabled
            control that explains itself is more honest than a button that
            silently does nothing. */}
        <div className="mt-[var(--space-5)] border-t border-[var(--border-subtle)] pt-[var(--space-4)]">
          <p className={labelClasses}>{briefPanelCopy.sourcesLabel}</p>

          <div className="mt-[var(--space-2)] flex flex-wrap items-center gap-[var(--space-2)]">
            <SourceButton icon={<Paperclip size={14} strokeWidth={1.75} />}>
              {briefPanelCopy.attachLabel}
            </SourceButton>
            <SourceButton icon={<Link2 size={14} strokeWidth={1.75} />}>
              {briefPanelCopy.urlLabel}
            </SourceButton>
            <SourceButton icon={<Upload size={14} strokeWidth={1.75} />}>
              {briefPanelCopy.uploadLabel}
            </SourceButton>
            <SourceButton icon={<Wand2 size={14} strokeWidth={1.75} />}>
              {briefPanelCopy.enhanceLabel}
            </SourceButton>
          </div>

          <p className={cn("mt-[var(--space-2)]", hintClasses)}>{briefPanelCopy.sourcesHint}</p>
        </div>
      </CardBody>
    </Card>
  );
}

/** A brief source action. Always disabled for now — see BriefCard. */
function SourceButton({ children, icon }: { children: ReactNode; icon: ReactNode }) {
  return (
    <button
      type="button"
      disabled
      className={cn(
        "flex h-8 cursor-not-allowed items-center gap-[var(--space-2)]",
        "rounded-[var(--radius-control)] border border-[var(--border-default)] px-[var(--space-3)]",
        "text-[length:var(--text-app-cell)] text-[color:var(--text-muted)] opacity-70",
      )}
    >
      <span aria-hidden="true" className="shrink-0">
        {icon}
      </span>
      {children}
    </button>
  );
}

