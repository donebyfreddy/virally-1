/** Quick templates. Configures the campaign's shape; never writes the brief. */
function TemplatePanel({
  activeId,
  onApply,
}: {
  activeId: string | null;
  onApply: (id: string) => void;
}) {
  return (
    <Panel id="templates" className="scroll-mt-[var(--space-24)]">
      <div className="flex flex-wrap items-baseline justify-between gap-[var(--space-4)]">
        <h2 className="font-utility text-[length:var(--text-utility-xs)] uppercase tracking-[var(--tracking-eyebrow)] text-[color:var(--color-text-secondary)]">
          {briefPanelCopy.templatesHeading}
        </h2>
        <p className="text-[length:var(--text-app-meta)] text-[color:var(--color-text-muted)]">
          {briefPanelCopy.templatesHint}
        </p>
      </div>

      <ul className="mt-[var(--space-4)] grid gap-[var(--space-3)] sm:grid-cols-2 lg:grid-cols-4">
        {TEMPLATES.map((template) => {
          const active = template.id === activeId;
          return (
            <li key={template.id}>
              <button
                type="button"
                onClick={() => onApply(template.id)}
                aria-pressed={active}
                className={cn(
                  "flex h-full w-full flex-col items-start gap-[var(--space-2)] rounded-[var(--radius-sm)] p-[var(--space-4)] text-left",
                  "transition-colors duration-[var(--dur-instant)] ease-[var(--ease-cut)]",
                  "focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[var(--color-focus)]",
                  active
                    ? "border-2 border-[var(--color-action)] bg-[var(--color-action-wash)] p-[calc(var(--space-4)-1px)]"
                    : "border border-[var(--color-border-hairline)] bg-[var(--color-surface-2)] hover:border-[var(--color-border)]",
                )}
              >
                <span className="text-[length:var(--text-app-cell)] text-[color:var(--color-text-primary)]">
                  {template.label}
                </span>

                <span className="font-utility text-[length:var(--text-utility-xs)] tabular-nums text-[color:var(--color-text-muted)]">
                  {template.range} · {template.concepts} concepts
                </span>

                {/* What the brief must cover. This is the template's actual
                    value — it tells the user what to write rather than writing
                    it for them. */}
                <span className="mt-[var(--space-1)] flex flex-col gap-0.5">
                  {template.covers.map((item) => (
                    <span
                      key={item}
                      className="flex gap-[var(--space-2)] text-[length:var(--text-utility-xs)] text-[color:var(--color-text-muted)]"
                    >
                      <span aria-hidden="true">·</span>
                      {item}
                    </span>
                  ))}
                </span>

                {active && (
                  <span className="mt-auto pt-[var(--space-2)] font-utility text-[length:var(--text-utility-xs)] uppercase tracking-[var(--tracking-utility)] text-[color:var(--color-action)]">
                    Applied
                  </span>
                )}
              </button>
            </li>
          );
        })}
      </ul>
    </Panel>
  );
}

/**
 * The plan summary rail.
 *
 * Every figure here is computed by `lib/content/plan` from the current form
 * state — the same module the server re-runs on submit. Nothing is illustrative.
 */
function PlanRail({
  estimate,
  errors,
  stage,
  onStageChange,
  gateOnConfirmation,
  confirmed,
  onConfirmedChange,
  canSubmit,
  promptReady,
}: {
  estimate: ReturnType<typeof estimateCost>;
  errors: readonly string[];
  stage: GenerationStageId;
  onStageChange: (next: GenerationStageId) => void;
  gateOnConfirmation: boolean;
  confirmed: boolean;
  onConfirmedChange: (next: boolean) => void;
  canSubmit: boolean;
  promptReady: boolean;
}) {
  const { counts } = estimate;

  return (
    <aside className="flex min-w-0 flex-col gap-[var(--space-4)] xl:sticky xl:top-[var(--space-6)]">
      <RailPanel title={planSummaryCopy.heading} accent id="plan-summary">
        <p className="text-[length:var(--text-app-meta)] leading-[var(--leading-snug)] text-[color:var(--color-text-secondary)]">
          {planSummaryCopy.intro}
        </p>

        {errors.length > 0 && (
          <div className="mt-[var(--space-4)]">
            <ErrorState
              title="PLAN NOT VALID"
              body={errors.join(" ")}
              reassurance="Nothing has been created and no credits have been used."
            />
          </div>
        )}

        <div className="mt-[var(--space-4)]">
          <RailList>
            <RailRow
              label="Content items"
              value={counts.contentItems.toLocaleString("en-US")}
              icon={<FileText size={14} strokeWidth={1.5} />}
            />
            <RailRow
              label="Variants to publish"
              value={counts.variants.toLocaleString("en-US")}
              icon={<Layers size={14} strokeWidth={1.5} />}
            />
            <RailRow
              label="Videos to generate"
              value={counts.videos.toLocaleString("en-US")}
              icon={<Film size={14} strokeWidth={1.5} />}
            />
            <RailRow
              label="Renders"
              value={counts.renders.toLocaleString("en-US")}
              icon={<Monitor size={14} strokeWidth={1.5} />}
            />
            {counts.voiceovers > 0 && (
              <RailRow
                label="Voiceovers"
                value={counts.voiceovers.toLocaleString("en-US")}
                icon={<Mic size={14} strokeWidth={1.5} />}
              />
            )}
            {counts.publishJobs > 0 && (
              <RailRow
                label="Publishing jobs"
                value={counts.publishJobs.toLocaleString("en-US")}
                icon={<Radio size={14} strokeWidth={1.5} />}
              />
            )}

            <RailRow
              label="Total jobs"
              value={counts.totalJobs.toLocaleString("en-US")}
              divided
            />

            {/* Rendered only when provider throughput is actually known. The
                brief permits a time estimate from measured throughput and from
                nothing else, so with no provider configured there is no row
                here rather than an invented range. */}
            {estimate.estimatedMinutes !== null && (
              <RailRow
                label="Estimated time"
                value={`~${estimate.estimatedMinutes.low}–${estimate.estimatedMinutes.high} min`}
              />
            )}

            {/* Credits first, then the cash equivalent. Credits are the unit the
                user's balance is denominated in, so that is the number that
                answers "can I afford this"; the currency figure is the
                explanation of it, not the headline. */}
            <RailRow
              label="Estimated credits"
              value={estimate.credits.toLocaleString("en-US")}
              emphasis
            />
            <RailRow label="Equivalent cost" value={formatCents(estimate.totalCents)} />
          </RailList>
        </div>

        {estimate.estimatedMinutes === null && (
          <p className="mt-[var(--space-3)] text-[length:var(--text-utility-xs)] leading-[var(--leading-snug)] text-[color:var(--color-text-muted)]">
            {costCopy.noTimeEstimate}
          </p>
        )}
      </RailPanel>

      <RailPanel title={planSummaryCopy.statusHeading} id="plan-status">
        <p className="flex items-center gap-[var(--space-2)] text-[length:var(--text-app-cell)] text-[color:var(--color-text-primary)]">
          {/* Not the machine-working teal: nothing is running yet. A neutral
              settled state, with the word carrying the meaning. */}
          <span
            aria-hidden="true"
            className={cn(
              "size-1.5 shrink-0 rounded-full",
              promptReady
                ? "bg-[var(--color-action)]"
                : "bg-[var(--color-text-muted)]",
            )}
          />
          {promptReady ? planSummaryCopy.readyLabel : planSummaryCopy.blockedLabel}
        </p>
        <p className="mt-[var(--space-2)] text-[length:var(--text-app-meta)] text-[color:var(--color-text-muted)]">
          {promptReady
            ? planSummaryCopy.readyDetail
            : "Write a brief of at least ten characters to continue."}
        </p>
      </RailPanel>

      <RailPanel title={costCopy.stageHeading} id="plan-stage">
        <p className="text-[length:var(--text-app-meta)] leading-[var(--leading-snug)] text-[color:var(--color-text-muted)]">
          {costCopy.stageHint}
        </p>

        <div className="mt-[var(--space-4)] flex flex-col gap-[var(--space-2)]">
          {GENERATION_STAGES.map((option) => (
            <label
              key={option.id}
              className={cn(
                "flex min-h-11 cursor-pointer items-start gap-[var(--space-3)] rounded-[var(--radius-sm)] p-[var(--space-3)]",
                "transition-colors duration-[var(--dur-instant)]",
                stage === option.id
                  ? "border-2 border-[var(--color-action)] bg-[var(--color-action-wash)] p-[calc(var(--space-3)-1px)]"
                  : "border border-[var(--color-border-hairline)] hover:border-[var(--color-border)]",
              )}
            >
              <input
                type="radio"
                name="stageChoice"
                value={option.id}
                checked={stage === option.id}
                onChange={() => onStageChange(option.id)}
                className="sr-only"
              />
              <span
                aria-hidden="true"
                className="w-3 shrink-0 font-utility text-[color:var(--color-action)]"
              >
                {stage === option.id ? "✓" : ""}
              </span>
              <span className="flex min-w-0 flex-col">
                <span className="text-[length:var(--text-app-cell)] text-[color:var(--color-text-primary)]">
                  {option.label}
                  {!option.cheap && (
                    <Badge tone="warning" className="ml-[var(--space-2)]">
                      Spends credits
                    </Badge>
                  )}
                </span>
                <span className="text-[length:var(--text-utility-xs)] text-[color:var(--color-text-muted)]">
                  {option.produces}
                </span>
              </span>
            </label>
          ))}
        </div>

        {gateOnConfirmation && (
          <div className="mt-[var(--space-4)] flex flex-col gap-[var(--space-3)] rounded-[var(--radius-sm)] border border-[var(--color-warning)] p-[var(--space-4)]">
            <p className="font-utility text-[length:var(--text-utility-xs)] uppercase tracking-[var(--tracking-utility)] text-[color:var(--color-warning)]">
              {costCopy.confirmHeading}
            </p>
            <p className="text-[length:var(--text-app-meta)] text-[color:var(--color-text-secondary)]">
              This will create {estimate.counts.totalJobs.toLocaleString("en-US")} jobs and may use
              significant generation credits. Jobs run in controlled batches. Reviewing concepts
              first avoids unnecessary cost.
            </p>
            <label className="flex min-h-11 cursor-pointer items-center gap-[var(--space-3)] text-[length:var(--text-app-meta)] text-[color:var(--color-text-primary)]">
              <input
                type="checkbox"
                name="confirmed"
                checked={confirmed}
                onChange={(event) => onConfirmedChange(event.target.checked)}
                className="size-4"
              />
              {costCopy.confirmCheckboxLabel}
            </label>
          </div>
        )}

        <Button type="submit" size="lg" className="mt-[var(--space-4)] w-full" disabled={!canSubmit}>
          {createCopy.submitLabel}
        </Button>
      </RailPanel>

      <RailNote
        title={planSummaryCopy.whyHeading}
        body={planSummaryCopy.whyBody}
        icon={<Target size={14} strokeWidth={1.5} />}
      />
    </aside>
  );
}

function NumberField({
  label,
  value,
  min,
  max,
  hint,
  onChange,
}: {
  label: string;
  value: number;
  min: number;
  max: number;
  hint: string;
  onChange: (next: number) => void;
}) {
  const id = `composer-${label.toLowerCase().replace(/\s+/g, "-")}`;

  return (
    <div className="flex flex-col gap-[var(--space-1)]">
      <label
        htmlFor={id}
        className="font-utility text-[length:var(--text-utility-xs)] uppercase tracking-[var(--tracking-eyebrow)] text-[color:var(--color-text-muted)]"
      >
        {label}
      </label>
      <input
        id={id}
        type="number"
        inputMode="numeric"
        min={min}
        max={max}
        value={value}
        aria-describedby={`${id}-hint`}
        onChange={(event) => {
          const next = Number(event.target.value);
          // Clamped on input rather than on submit: an out-of-range value would
          // otherwise silently change the estimate the user is reading.
          if (Number.isFinite(next)) onChange(Math.min(max, Math.max(min, Math.trunc(next))));
        }}
        className={cn(
          "min-h-11 w-full rounded-[var(--radius-sm)] border border-[var(--color-border-hairline)]",
          "bg-[var(--color-surface-2)] px-[var(--space-3)]",
          "font-utility text-[length:var(--text-app-cell)] tabular-nums text-[color:var(--color-text-primary)]",
          "transition-colors duration-[var(--dur-instant)]",
          "hover:border-[var(--color-border)]",
        )}
      />
      <p id={`${id}-hint`} className="text-[length:var(--text-utility-xs)] text-[color:var(--color-text-muted)]">
        {hint}
      </p>
    </div>
  );
}
