/**
 * Goal, tone and languages.
 *
 * There is no audience field: who the campaign is for is part of the brief prose
 * and is not stored as its own column, so a control here would be a form field
 * with nowhere to go.
 */
function AudienceCard({
  goal,
  onGoalChange,
  tone,
  onToneChange,
  languages,
  onLanguagesChange,
}: {
  goal: string;
  onGoalChange: (next: string) => void;
  tone: string;
  onToneChange: (next: string) => void;
  languages: readonly string[];
  onLanguagesChange: (next: string[]) => void;
}) {
  const languagesId = useId();

  return (
    <Card as="section" aria-labelledby="audience-heading">
      <CardHeader id="audience-heading" as="h2" title={briefPanelCopy.audienceHeading} />

      <CardBody className="grid gap-[var(--space-4)] pt-[var(--space-3)] sm:grid-cols-2">
        <SelectField
          label="Primary goal"
          value={goal}
          onChange={onGoalChange}
          options={GOAL_OPTIONS}
        />
        <SelectField
          label="Tone of voice"
          value={tone}
          onChange={onToneChange}
          options={TONE_OPTIONS}
        />

        <div className="flex min-w-0 flex-col gap-[var(--space-1)]">
          <label htmlFor={languagesId} className={labelClasses}>
            Languages
          </label>
          <input
            id={languagesId}
            value={languages.join(", ")}
            aria-describedby={`${languagesId}-hint`}
            onChange={(event) =>
              onLanguagesChange(
                event.target.value
                  .split(",")
                  .map((value) => value.trim())
                  .filter(Boolean),
              )
            }
            className={controlClasses}
          />
          <p id={`${languagesId}-hint`} className={hintClasses}>
            Comma separated. Each is a separate script.
          </p>
        </div>
      </CardBody>
    </Card>
  );
}

