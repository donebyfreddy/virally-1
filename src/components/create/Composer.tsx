/**
 * The campaign composer.
 *
 * Counts and cost are computed on every change from the same pure module the server
 * uses (`lib/content/plan`), so the number in the summary rail is the number the
 * server will act on. Two implementations of that arithmetic would eventually disagree,
 * and the disagreement would be a bill the user did not agree to.
 *
 * Nothing is generated by this component. It builds a request and hands it to a server
 * action; the safe default stage is "plans only".
 *
 * Layout follows the product's brief-then-plan model: the brief and its shape on
 * the left, the consequences on the right, visible at the moment the user
 * changes something rather than after they submit.
 */

/** Format chips, in the reference's order. Ratio ids come from RATIO_OPTIONS. */
const FORMAT_ICONS: Readonly<Record<AspectRatio, typeof Film>> = {
  "9:16": Film,
  "4:5": ImageIcon,
  "1:1": Square,
  "16:9": Monitor,
  "4:3": Monitor,
  "3:2": ImageIcon,
  custom: Layers,
};

export function Composer({
  onSubmit,
  accountCount,
  defaultLanguage,
}: {
  onSubmit: (payload: FormData) => void;
  accountCount: number;
  defaultLanguage: string;
}) {
  const [prompt, setPrompt] = useState("");
  const [platforms, setPlatforms] = useState<Platform[]>(["instagram", "tiktok"]);
  const [ratios, setRatios] = useState<AspectRatio[]>(["9:16"]);
  const [languages, setLanguages] = useState<string[]>([defaultLanguage]);
  const [concepts, setConcepts] = useState(3);
  const [hooksPerConcept, setHooksPerConcept] = useState(2);
  const [durationSeconds, setDurationSeconds] = useState(20);
  const [quality, setQuality] = useState<Quality>("standard");
  const [withVoiceover, setWithVoiceover] = useState(true);
  const [withThumbnail, setWithThumbnail] = useState(false);
  const [stage, setStage] = useState<GenerationStageId>(DEFAULT_STAGE);
  const [confirmed, setConfirmed] = useState(false);

  // The three campaign-shape controls. Each is persisted: length becomes the
  // campaign's date range, tone reaches the language provider, goal becomes the
  // campaign objective. None of them is a decorative field.
  const [lengthDays, setLengthDays] = useState(String(DEFAULT_LENGTH_DAYS));
  const [tone, setTone] = useState(TONE_OPTIONS[0]?.id ?? "confident");
  const [goal, setGoal] = useState(GOAL_OPTIONS[0]?.id ?? "product_awareness");

  /** Which template configured the current shape, for the selected state. */
  const [templateId, setTemplateId] = useState<string | null>(null);

  const request: PlanRequest = useMemo(
    () => ({
      concepts,
      hooksPerConcept,
      platforms,
      ratios,
      languages,
      accountCount,
      withVoiceover,
      withThumbnail,
      durationSeconds,
      quality,
    }),
    [
      concepts,
      hooksPerConcept,
      platforms,
      ratios,
      languages,
      accountCount,
      withVoiceover,
      withThumbnail,
      durationSeconds,
      quality,
    ],
  );

  const errors = useMemo(() => validatePlanRequest(request), [request]);
  const estimate = useMemo(() => estimateCost(request), [request]);
  const needsConfirmation = requiresConfirmation(estimate.counts);

  // Only the render stage actually spends the full estimate, so confirmation is
  // demanded for that combination rather than for any large plan.
  const gateOnConfirmation = needsConfirmation && stage === "render";
  const promptReady = prompt.trim().length >= 10;
  const canSubmit = promptReady && errors.length === 0 && (!gateOnConfirmation || confirmed);

  function toggle<T>(list: T[], value: T, setter: (next: T[]) => void, atLeastOne = true) {
    const has = list.includes(value);
    const next = has ? list.filter((item) => item !== value) : [...list, value];
    // Never allow an empty selection where the plan needs at least one — the user
    // would otherwise have to guess why the estimate disappeared.
    if (atLeastOne && next.length === 0) return;
    setter(next);
  }

  /**
   * Applies a template's structure only.
   *
   * The brief text is untouched by design — see the note on TEMPLATES. Writing
   * prose the user did not choose would anchor their first campaign on our
   * phrasing, so the template sets the shape and the user supplies the words.
   */
  function applyTemplate(id: string) {
    const template = TEMPLATES.find((item) => item.id === id);
    if (!template) return;
    setTemplateId(id);
    setLengthDays(String(template.days));
    setConcepts(template.concepts);
    setGoal(template.goal);
  }

  return (
    <form
      action={onSubmit}
      className="grid items-start gap-[var(--space-6)] xl:grid-cols-[minmax(0,1fr)_var(--app-summary-rail)]"
    >
      {/* Hidden fields carry the resolved request so the server does not re-derive it
          from loose inputs and risk computing something different. */}
      <input type="hidden" name="prompt" value={prompt} />
      <input type="hidden" name="platforms" value={platforms.join(",")} />
      <input type="hidden" name="ratios" value={ratios.join(",")} />
      <input type="hidden" name="languages" value={languages.join(",")} />
      <input type="hidden" name="concepts" value={concepts} />
      <input type="hidden" name="hooksPerConcept" value={hooksPerConcept} />
      <input type="hidden" name="durationSeconds" value={durationSeconds} />
      <input type="hidden" name="quality" value={quality} />
      <input type="hidden" name="withVoiceover" value={String(withVoiceover)} />
      <input type="hidden" name="withThumbnail" value={String(withThumbnail)} />
      <input type="hidden" name="stage" value={stage} />
      <input type="hidden" name="lengthDays" value={lengthDays} />
      <input type="hidden" name="tone" value={tone} />
      <input type="hidden" name="goal" value={goal} />

      <div className="flex min-w-0 flex-col gap-[var(--space-6)]">
        <BriefPanel
          prompt={prompt}
          onPromptChange={setPrompt}
          promptReady={promptReady}
          canSubmit={canSubmit}
        />

        <ShapePanel
          lengthDays={lengthDays}
          onLengthChange={(next) => {
            setLengthDays(next);
            // The shape no longer matches the template that set it.
            setTemplateId(null);
          }}
          tone={tone}
          onToneChange={setTone}
          goal={goal}
          onGoalChange={(next) => {
            setGoal(next);
            setTemplateId(null);
          }}
          platforms={platforms}
          onPlatformToggle={(id) => toggle(platforms, id, setPlatforms)}
          ratios={ratios}
          onRatioToggle={(id) => toggle(ratios, id, setRatios)}
          quality={quality}
          onQualityChange={setQuality}
          concepts={concepts}
          onConceptsChange={(next) => {
            setConcepts(next);
            setTemplateId(null);
          }}
          hooksPerConcept={hooksPerConcept}
          onHooksChange={setHooksPerConcept}
          durationSeconds={durationSeconds}
          onDurationChange={setDurationSeconds}
          withVoiceover={withVoiceover}
          onVoiceoverToggle={() => setWithVoiceover((value) => !value)}
          withThumbnail={withThumbnail}
          onThumbnailToggle={() => setWithThumbnail((value) => !value)}
          languages={languages}
          onLanguagesChange={setLanguages}
        />

        <TemplatePanel activeId={templateId} onApply={applyTemplate} />
      </div>

      <PlanRail
        estimate={estimate}
        errors={errors.map((error) => error.message)}
        stage={stage}
        onStageChange={(next) => {
          setStage(next);
          // Re-arm confirmation when the expensive option is chosen.
          setConfirmed(false);
        }}
        gateOnConfirmation={gateOnConfirmation}
        confirmed={confirmed}
        onConfirmedChange={setConfirmed}
        canSubmit={canSubmit}
        promptReady={promptReady}
      />
    </form>
  );
}

/** The brief input and its source actions. */
function BriefPanel({
  prompt,
  onPromptChange,
  promptReady,
  canSubmit,
}: {
  prompt: string;
  onPromptChange: (next: string) => void;
  promptReady: boolean;
  canSubmit: boolean;
}) {
  const MAX = 4000;

  return (
    <Panel pad="none" className="overflow-hidden">
      <div className="flex items-center justify-between gap-[var(--space-4)] border-b border-[var(--color-border-hairline)] px-[var(--app-panel-pad)] py-[var(--space-4)]">
        <h2 className="flex items-center gap-[var(--space-2)] font-utility text-[length:var(--text-utility-xs)] uppercase tracking-[var(--tracking-eyebrow)] text-[color:var(--color-text-secondary)]">
          <FileText aria-hidden="true" size={14} strokeWidth={1.5} />
          {briefPanelCopy.heading}
        </h2>

        <span
          className={cn(
            "font-utility text-[length:var(--text-utility-xs)] tabular-nums",
            prompt.length > MAX * 0.9
              ? "text-[color:var(--color-warning)]"
              : "text-[color:var(--color-text-muted)]",
          )}
        >
          {prompt.length.toLocaleString("en-US")} / {MAX.toLocaleString("en-US")}
        </span>
      </div>

      <div className="px-[var(--app-panel-pad)] py-[var(--space-4)]">
        {/* A real label, not placeholder-only instruction. Visually hidden
            because the panel heading already names the field on screen, but the
            hint below it is rendered for everyone — essential instructions
            never live only in a placeholder. */}
        <label htmlFor="campaign-brief" className="sr-only">
          {createCopy.promptLabel}
        </label>

        <textarea
          id="campaign-brief"
          name="promptVisible"
          rows={6}
          value={prompt}
          maxLength={MAX}
          onChange={(event) => onPromptChange(event.target.value)}
          aria-describedby="campaign-brief-hint"
          placeholder={createCopy.examples[0]}
          className={cn(
            "w-full resize-y bg-transparent",
            "text-[length:var(--text-body-s)] leading-[var(--leading-snug)] text-[color:var(--color-text-primary)]",
            "placeholder:italic placeholder:text-[color:var(--color-text-muted)]",
            "focus:outline-none",
          )}
        />

        <p
          id="campaign-brief-hint"
          className="mt-[var(--space-3)] text-[length:var(--text-app-meta)] text-[color:var(--color-text-muted)]"
        >
          {createCopy.promptHint}
        </p>
      </div>

      <div className="flex flex-wrap items-center gap-[var(--space-2)] border-t border-[var(--color-border-hairline)] bg-[var(--color-surface-2)] px-[var(--app-panel-pad)] py-[var(--space-3)]">
        {/* Source actions. Disabled and labelled rather than hidden: the product
            will accept these sources, and a disabled control with a reason is
            more honest than a button that silently does nothing. */}
        <ToolbarButton icon={<Paperclip size={14} strokeWidth={1.5} />} disabled>
          {briefPanelCopy.attachLabel}
        </ToolbarButton>
        <ToolbarButton icon={<Link2 size={14} strokeWidth={1.5} />} disabled>
          {briefPanelCopy.urlLabel}
        </ToolbarButton>
        <ToolbarButton icon={<Upload size={14} strokeWidth={1.5} />} disabled>
          {briefPanelCopy.uploadLabel}
        </ToolbarButton>

        <span className="ml-auto flex items-center gap-[var(--space-2)]">
          <ToolbarButton icon={<Wand2 size={14} strokeWidth={1.5} />} emphasis disabled>
            {briefPanelCopy.enhanceLabel}
          </ToolbarButton>

          {/* The real submit. Placed here as well as in the rail because this is
              where the user's hands are after typing the brief. */}
          <Button type="submit" disabled={!canSubmit}>
            {briefPanelCopy.generateLabel}
          </Button>
        </span>
      </div>

      {!promptReady && prompt.length > 0 && (
        <p className="border-t border-[var(--color-border-hairline)] px-[var(--app-panel-pad)] py-[var(--space-3)] text-[length:var(--text-app-meta)] text-[color:var(--color-text-muted)]">
          Write at least ten characters to continue.
        </p>
      )}
    </Panel>
  );
}

